#!/usr/bin/env node
/* ════════════════════════════════════════════════════════════════════════
   GENERATE MANIFEST — turns the content mirrored into R2 into the gallery's
   data file (src/lib/generated/media.ts).

   Reads the R2 structure  2026/{NN_Month}/{YYYY-MM-DD}/{Category}/{Project}/imgs
   and produces one entry per project: title (project folder), category, date,
   cover (the _Preview image), and the ordered image set (the album).

   Run after syncing new content to R2:
     node scripts/gen-manifest.mjs
   Needs: rclone configured with an `r2` remote, and R2_PUBLIC_URL + R2_BUCKET
   in .env.local.
   ──────────────────────────────────────────────────────────────────────── */

import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

// ── env ─────────────────────────────────────────────────────────────────────
const env = {};
for (const line of readFileSync('.env.local', 'utf8').split('\n')) {
  const i = line.indexOf('=');
  if (i > 0 && !line.startsWith('#')) env[line.slice(0, i).trim()] = line.slice(i + 1).trim();
}
const BASE = (env.R2_PUBLIC_URL || '').replace(/\/$/, '');
const BUCKET = env.R2_BUCKET || 'constrcut-media';
if (!BASE) {
  console.error('R2_PUBLIC_URL missing from .env.local');
  process.exit(1);
}

// ── list files in R2 under 2026/ ────────────────────────────────────────────
const raw = execSync(`rclone lsf -R --files-only "r2:${BUCKET}/2026"`, {
  encoding: 'utf8',
  maxBuffer: 256 * 1024 * 1024,
});
const files = raw
  .split('\n')
  .map((s) => s.trim())
  .filter(Boolean)
  .map((p) => `2026/${p}`);

// ── helpers ─────────────────────────────────────────────────────────────────
const DATE_RE = /(\d{4}-\d{2}-\d{2})/;
const slugify = (s) =>
  s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const encodePath = (p) => p.split('/').map(encodeURIComponent).join('/');
const toUrl = (p) => `${BASE}/${encodePath(p)}`;
const basename = (p) => p.slice(p.lastIndexOf('/') + 1);
const isImage = (f) => /\.(png|jpe?g|webp|gif|avif)$/i.test(f);
const isPreview = (f) => basename(f).toLowerCase().startsWith('_preview');
const leadNum = (name) => {
  const m = name.match(/^\s*(\d+)/);
  return m ? parseInt(m[1], 10) : 9999;
};

// ── group files by their project folder (the dir that holds the images) ─────
const projects = new Map();
for (const f of files) {
  if (!isImage(f)) continue;
  const dir = f.slice(0, f.lastIndexOf('/'));
  if (!projects.has(dir)) projects.set(dir, []);
  projects.get(dir).push(f);
}

const items = [];
for (const [dir, imgs] of projects) {
  const segs = dir.split('/'); // 2026 / NN_Month / DATE / [CATEGORY] / PROJECT
  const project = segs[segs.length - 1];
  const dateSeg = segs.find((s) => DATE_RE.test(s));
  const date = dateSeg ? dateSeg.match(DATE_RE)[1] : '';
  const dateIdx = dateSeg ? segs.indexOf(dateSeg) : -1;
  const projIdx = segs.length - 1;
  const categoryName =
    dateIdx >= 0 && projIdx - dateIdx >= 2 ? segs[dateIdx + 1] : 'Uncategorized';

  const preview = imgs.find(isPreview);
  const slides = imgs
    .filter((f) => !isPreview(f))
    .sort((a, b) => leadNum(basename(a)) - leadNum(basename(b)));

  const cover = preview ? toUrl(preview) : toUrl(slides[0] ?? imgs[0]);
  const images = (slides.length ? slides : imgs).map(toUrl);

  items.push({
    id: slugify(`${date}-${project}`),
    title: project.trim(),
    category: slugify(categoryName),
    categoryName,
    date,
    kind: 'image',
    thumb: cover,
    images,
  });
}

// newest first
items.sort((a, b) => (b.date || '').localeCompare(a.date || ''));

// ── write the generated module ──────────────────────────────────────────────
mkdirSync('src/lib/generated', { recursive: true });
const banner =
  `// AUTO-GENERATED by scripts/gen-manifest.mjs — do not edit by hand.\n` +
  `// Regenerate after syncing content to R2:  node scripts/gen-manifest.mjs\n` +
  `import type { MediaItem } from '@/lib/types';\n\n`;
writeFileSync(
  'src/lib/generated/media.ts',
  banner + `export const GENERATED_MEDIA: MediaItem[] = ${JSON.stringify(items, null, 2)};\n`,
);

const cats = [...new Set(items.map((i) => i.categoryName))];
console.log(`Wrote ${items.length} projects (${files.length} files).`);
console.log(`Categories: ${cats.join(', ')}`);
